"""Tokenize a conversation and build SFT labels that only train on assistant generations.

Method: render the whole conversation to text with the model's chat template, tokenize it in
one go (exactly like at inference), then use the tokenizer's ``offset_mapping`` to find which
tokens fall inside the text the assistant generates. Every other token gets ``IGNORE_INDEX``.

What the model generates at inference (and is therefore trained on):
    <|im_start|>assistant\n  Il fait 18°C.<|im_end|>  \n
    └───── prompt ───────┘  └────── trained ──────┘  └ prompt
"""

from collections.abc import Mapping, Sequence
from dataclasses import dataclass
from pathlib import Path
from typing import Any, cast

from transformers import PreTrainedTokenizerBase

from post_training.data.conversation import load_jsonl
from post_training.data.prompt_format import bfcl_chat_template

# Label value skipped by PyTorch's cross-entropy (default `ignore_index` of `F.cross_entropy`).
IGNORE_INDEX = -100


@dataclass(frozen=True)
class ChatFormat:
    """Markers delimiting what the assistant generates in the rendered text.

    `assistant_header` is written by us at inference (`add_generation_prompt=True`), so it is
    not trained. `end_of_turn` is generated by the model to stop (it is the EOS), so it is.
    """

    assistant_header: str
    end_of_turn: str


CHATML = ChatFormat(assistant_header="<|im_start|>assistant\n", end_of_turn="<|im_end|>")


@dataclass(frozen=True)
class TokenizedExample:
    input_ids: list[int]
    labels: list[int]


def find_assistant_spans(text: str, chat_format: ChatFormat) -> list[tuple[int, int]]:
    """Return `[start, end)` character spans of assistant generations, `end_of_turn` included."""
    spans: list[tuple[int, int]] = []
    cursor = 0
    while (header := text.find(chat_format.assistant_header, cursor)) != -1:
        start = header + len(chat_format.assistant_header)
        eot = text.find(chat_format.end_of_turn, start)
        if eot == -1:
            raise ValueError(f"Assistant turn starting at char {start} is never closed.")
        end = eot + len(chat_format.end_of_turn)
        spans.append((start, end))
        cursor = end
    return spans


def tokenize_with_labels(
    messages: Sequence[Mapping[str, Any]],
    tokenizer: PreTrainedTokenizerBase,
    tools: Sequence[Mapping[str, Any]] | None = None,
    chat_format: ChatFormat = CHATML,
    chat_template: str | None = None,
) -> TokenizedExample:
    """Tokenize `messages` and mask every token the model does not generate at inference.

    `chat_template` overrides the tokenizer's template (e.g. `bfcl_chat_template(tokenizer)`).
    """
    text = tokenizer.apply_chat_template(
        # transformers annotates these as `list[dict[str, str]]`, which is too narrow for
        # tool calls (nested dicts); the runtime accepts any JSON-like structure.
        cast(list[dict[str, str]], [dict(m) for m in messages]),
        tools=[dict(t) for t in tools] if tools else None,
        chat_template=chat_template,
        tokenize=False,
    )
    if not isinstance(text, str):
        raise TypeError(f"Expected the chat template to render a string, got {type(text)}.")

    spans = find_assistant_spans(text, chat_format)
    # Sanity check: a marker string inside user content would create a fake span (and a
    # template that drops a turn would lose one). Either way the labels would be wrong.
    n_assistant = sum(m["role"] == "assistant" for m in messages)
    if len(spans) != n_assistant:
        raise ValueError(
            f"Found {len(spans)} assistant spans in the rendered text but the conversation "
            f"has {n_assistant} assistant messages. Check the chat format markers."
        )

    # The template already contains the special tokens it needs (BOS included, if any).
    encoding = tokenizer(text, add_special_tokens=False, return_offsets_mapping=True)
    input_ids: list[int] = encoding["input_ids"]
    offsets: list[tuple[int, int]] = encoding["offset_mapping"]

    labels = [IGNORE_INDEX] * len(input_ids)
    for i, (token_start, _) in enumerate(offsets):
        # A token is trained if it *starts* inside a generated span. A token that straddles
        # the header boundary (e.g. "\n" of the header merged with leading "\n\n" of the
        # answer) starts in the prompt, so it stays masked: never train on prompt characters.
        if any(start <= token_start < end for start, end in spans):
            labels[i] = input_ids[i]

    return TokenizedExample(input_ids=input_ids, labels=labels)


def tokenize_file(path: Path, tokenizer: PreTrainedTokenizerBase) -> list[TokenizedExample]:
    """Tokenize a normalized conversations file exactly like the BFCL evaluation renders prompts.

    Used by the training script and the data checks, so they all see the very same
    token ids and labels.
    """
    template = bfcl_chat_template(tokenizer)
    return [
        tokenize_with_labels(c.messages, tokenizer, tools=c.tools, chat_template=template)
        for c in load_jsonl(path)
    ]
